enum TransportHubType {
  railwayStation,
  metroStation,
  busStation,
  airportRailLink,
  airportBusHub,
  intermodalStation;

  String get key => switch (this) {
    railwayStation => 'railway_station',
    metroStation => 'metro_station',
    busStation => 'bus_station',
    airportRailLink => 'airport_rail_link',
    airportBusHub => 'airport_bus_hub',
    intermodalStation => 'intermodal_station',
  };
}

